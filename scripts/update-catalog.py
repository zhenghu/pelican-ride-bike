#!/usr/bin/env python3
"""Refresh the local preview catalog without changing original artworks."""
import json
import re
import argparse
import hashlib
from datetime import date
from pathlib import Path

root = Path(__file__).resolve().parent.parent
alias_file = root / 'data' / 'animation-aliases.json'
aliases = json.loads(alias_file.read_text(encoding='utf-8')) if alias_file.exists() else {}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Validate review and generated catalog without writing files')
args = parser.parse_args()
ranking = json.loads((root / 'data' / 'quality-ranking.json').read_text(encoding='utf-8'))
date.fromisoformat(ranking['reviewedAt'])
for field in ('method', 'scope'):
    if not isinstance(ranking.get(field), str) or not ranking[field].strip():
        raise ValueError(f'Missing ranking {field}')
entries = ranking['entries']
files = {path.relative_to(root).as_posix() for path in (root / 'animations').glob('*.html')}
ranked_files = [entry['file'] for entry in entries]
if len(set(ranked_files)) != len(ranked_files) or set(ranked_files) != files:
    raise ValueError('Ranking must cover every animation exactly once; visually review and update data/quality-ranking.json')
if any(type(entry['rank']) is not int for entry in entries) or sorted(entry['rank'] for entry in entries) != list(range(1, len(entries) + 1)):
    raise ValueError('Quality ranks must be unique and consecutive, starting at 1')
for entry in entries:
    if not isinstance(entry.get('reason'), str) or not entry['reason'].strip():
        raise ValueError(f'Missing review reason: {entry["file"]}')
    if hashlib.sha256((root / entry['file']).read_bytes()).hexdigest() != entry['sha256']:
        raise ValueError(f'Animation changed since review: {entry["file"]}; visually re-review and rerank before updating its hash')
reviews = {entry['file']: entry for entry in entries}
models = []
for path in sorted((root / 'animations').glob('*.html'), key=lambda path: path.name.casefold()):
    source = path.read_text(encoding='utf-8')
    tech = []
    if re.search(r'<svg\b', source, re.I):
        tech.append('SVG')
    if re.search(r'<canvas\b', source, re.I):
        tech.append('Canvas')
    if '@keyframes' in source:
        tech.append('CSS 动画')
    if re.search(r'<animate(?:Transform|Motion)?\b', source):
        tech.append('SMIL')
    if 'requestAnimationFrame' in source:
        tech.append('JavaScript 动画')
    file = path.relative_to(root).as_posix()
    previous_names = [old for old, current in aliases.items() if current == file]
    legacy_aliases = list(dict.fromkeys(previous_names + [Path(old).name for old in previous_names]))
    review = reviews[file]
    models.append({'name': path.stem, 'file': file, 'aliases': legacy_aliases, 'tech': tech or ['HTML'],
                   'rank': review['rank'], 'review': review['reason']})
models.sort(key=lambda model: model['rank'])
output = root / 'data' / 'generated' / 'models.js'
content = (
    '// Generated by scripts/update-catalog.py\nwindow.PELICAN_MODELS = '
    + json.dumps(models, ensure_ascii=False, indent=2) + ';\nwindow.PELICAN_RANKING = '
    + json.dumps({key: ranking[key] for key in ('reviewedAt', 'method', 'scope')}, ensure_ascii=False, indent=2) + ';\n')
if args.check:
    if not output.exists() or output.read_text(encoding='utf-8') != content:
        raise ValueError('Generated catalog is stale; run python3 scripts/update-catalog.py')
    print(f'Validated quality ranking and catalog: {len(models)} versions')
else:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding='utf-8')
    print(f'Updated data/generated/models.js: {len(models)} ranked versions')
